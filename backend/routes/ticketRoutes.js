const router = require("express").Router();
const auth = require("../middlewares/authMiddleware");
const role = require("../middlewares/roleMiddleware");
const controller = require("../controllers/ticketController");
const commentRoutes = require("./commentRoutes");
const ratingController = require("../controllers/ratingController");
const { ratingSchema } = require("../validators/ratingValidator");
router.use(auth);
router.post("/", role("EMPLOYEE"), controller.create);
router.get("/", controller.list);
router.get("/:id/history", controller.history);
router.use("/:ticketId/comments", commentRoutes);
router.get("/:ticketId/ratings", ratingController.getForTicket);
router.post("/:ticketId/ratings", (req, res, next) => { try { req.body = ratingSchema.parse(req.body); next(); } catch (error) { next(error); } }, ratingController.create);
router.get("/:id", controller.getById);
router.put("/:id", controller.update);
router.patch("/:id/assign", role("ADMIN"), controller.assign);
router.patch("/:id/status", controller.status);
module.exports = router;
